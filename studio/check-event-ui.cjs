const {app,BrowserWindow,ipcMain,dialog}=require('electron');
const fs=require('node:fs');const path=require('node:path');
require('./electron.cjs');
const delay=ms=>new Promise(r=>setTimeout(r,ms));
app.whenReady().then(async()=>{try{
 while(!BrowserWindow.getAllWindows().length)await delay(100);
 const win=BrowserWindow.getAllWindows()[0];await delay(2000);
 await win.webContents.executeJavaScript("document.querySelector('.intro-bottom button')?.click()");
 let state=await win.webContents.executeJavaScript('window.axShell.getState()');
 if(state.phase!=='idle')throw Error(JSON.stringify(state));
 const font=await win.webContents.executeJavaScript("getComputedStyle(document.body).fontFamily");
 if(!font.includes('IBM Plex Sans KR'))throw Error(font);
 fs.copyFileSync(path.join(__dirname,'output/replay-fixture.series4.json'),path.join(__dirname,'output/ui-tools-fixture.series4.json'));
 dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path.join(__dirname,'output/ui-tools-fixture.series4.json')]});
 await win.webContents.executeJavaScript("window.axShell.command('open')");
 await delay(2000);
 const media=await win.webContents.executeJavaScript("(()=>{const v=document.querySelector('.compact-workspace video');return {src:v?.currentSrc,ready:v?.readyState,error:v?.error?.message,width:document.documentElement.scrollWidth,viewport:innerWidth}})()");
 if(media.ready<2||media.error)throw Error(JSON.stringify(media));
 const overlay=await win.webContents.executeJavaScript("(()=>{const ring=document.querySelector('.compact-workspace .video-click-ring');const label=document.querySelector('.compact-workspace .video-action-label');return {ring:!!ring,label:label?.textContent}})()");
 if(!overlay.ring)throw Error('Click overlay missing '+JSON.stringify(overlay));
 await win.webContents.executeJavaScript("document.querySelector('.compact-workspace .action-add-icon').click()");
 const form=await win.webContents.executeJavaScript("(()=>{const f=document.querySelector('.compact-workspace .action-add-form');return {visible:!!f,focused:document.activeElement?.tagName,options:[...f.querySelectorAll('option')].map(o=>o.value)}})()");
 if(!form.visible||form.options.length!==4)throw Error(JSON.stringify(form));
 const compact=await win.capturePage();fs.writeFileSync(path.join(__dirname,'output/playwright/event-tools-compact.png'),compact.toPNG());
 await win.webContents.executeJavaScript("document.querySelector('.compact-workspace .action-add-form').requestSubmit()");
 await delay(800);
 const afterAdd=await win.webContents.executeJavaScript('window.axShell.getState()');
 if(afterAdd.events.length!==2||afterAdd.events[1].kind!=='Wait')throw Error('UI add failed '+JSON.stringify(afterAdd));
 await win.webContents.executeJavaScript("document.querySelector('.compact-workspace .video-surface').requestFullscreen()",true);
 await delay(400);
 const full=await win.webContents.executeJavaScript("!!document.fullscreenElement?.querySelector('.video-action-overlay')");
 if(!full)throw Error('Fullscreen overlay missing');
 await win.webContents.executeJavaScript('document.exitFullscreen()');await delay(400);
 await win.webContents.executeJavaScript("document.querySelector('.mode-switch button').click()");await delay(500);
 await win.webContents.executeJavaScript("document.querySelector('.app .action-add-icon').click()");
 const bounds=win.getBounds();if(bounds.width<1000)throw Error(JSON.stringify(bounds));
 await delay(150);const studio=await win.capturePage();fs.writeFileSync(path.join(__dirname,'output/playwright/event-tools-studio.png'),studio.toPNG());
 console.log(JSON.stringify({ok:true,font,media,bounds,overlay,form,full,added:afterAdd.events[1].kind}));
 win.close();
 }catch(error){console.error(error);process.exitCode=1;BrowserWindow.getAllWindows().forEach(w=>w.close());}});
